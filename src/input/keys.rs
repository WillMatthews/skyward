/// Stable name for the settings file (`None`: not bindable).
pub fn name(k: KeyCode) -> Option<&'static str> {
    KEYS.iter().find(|e| e.0 == k).map(|e| e.1)
}

pub fn from_name(s: &str) -> Option<KeyCode> {
    KEYS.iter().find(|e| e.1 == s).map(|e| e.0)
}

/// Short label for the interface.
pub fn label(k: KeyCode) -> String {
    KEYS.iter().find(|e| e.0 == k).map(|e| e.2.to_string()).unwrap_or_else(|| format!("{k:?}"))
}
