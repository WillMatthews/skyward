/// Width of `text` in glyph units (at height [`HEIGHT`]).
pub fn width(text: &str) -> f32 {
    let n = text.chars().count();
    if n == 0 { 0.0 } else { n as f32 * ADVANCE - (ADVANCE - 4.0) }
}

/// Segments of `text` scaled to cap height `h` (m), left edge at x = 0,
/// baseline y = 0 (x right, y up in the text plane), and the text's width.
pub fn segments(text: &str, h: f32) -> (Vec<(Vec2, Vec2)>, f32) {
    let k = h / HEIGHT;
    let mut out = Vec::new();
    for (i, c) in text.chars().enumerate() {
        let x0 = i as f32 * ADVANCE;
        for line in glyph(c) {
            for w in line.windows(2) {
                out.push((vec2(x0 + w[0].0, w[0].1) * k, vec2(x0 + w[1].0, w[1].1) * k));
            }
        }
    }
    (out, width(text) * k)
}

/// Quads (4 corners each, in the text plane) for `text`: strokes `stroke`
/// glyph units wide, ends extended by half the width so joints close.
pub fn quads(text: &str, h: f32, stroke: f32) -> (Vec<[Vec2; 4]>, f32) {
    let (segs, w) = segments(text, h);
    let half = stroke * h / HEIGHT * 0.5;
    let q = segs
        .into_iter()
        .filter_map(|(a, b)| {
            let d = (b - a).try_normalize()?;
            let n = vec2(-d.y, d.x) * half;
            let (a, b) = (a - d * half, b + d * half);
            Some([a - n, b - n, b + n, a + n])
        })
        .collect();
    (q, w)
}

#[cfg(test)]
mod tests {
    #[test]
    fn every_sign_character_has_strokes() {
        for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-\u{2190}\u{2192}\u{2191}\u{2197}\u{2196}".chars() {
            assert!(!super::glyph(c).is_empty(), "{c}");
        }
        let (q, w) = super::quads("27L-09R", 1.0, super::STROKE);
        assert!(q.len() > 20 && w > 5.0 && w < 7.0, "{} {w}", q.len());
    }
}
